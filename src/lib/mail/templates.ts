/**
 * Email templates.
 *
 * Plain table-based HTML with inline styles, because that is what mail clients
 * actually render. Every value that reaches these functions is escaped — a
 * buyer complaint is untrusted text and it goes into an operator's inbox.
 */
import { env } from "@/lib/env";

export function esc(s: unknown): string {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

const INR = (n: number) => `₹${Math.trunc(n).toLocaleString("en-IN")}`;

function shell(title: string, bodyRows: string, accent = "#f97316"): string {
  return `<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title></head>
<body style="margin:0;padding:24px 12px;background:#f5f3ef;font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;color:#17202a;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="max-width:600px;margin:0 auto;background:#ffffff;border-radius:14px;overflow:hidden;box-shadow:0 1px 3px rgba(0,0,0,.08);">
  <tr><td style="background:${accent};padding:18px 26px;">
    <div style="font-size:19px;font-weight:700;color:#fff;letter-spacing:-.2px;">Vaanijya</div>
    <div style="font-size:12px;color:rgba(255,255,255,.88);margin-top:2px;">${esc(title)}</div>
  </td></tr>
  ${bodyRows}
  <tr><td style="padding:16px 26px 24px;border-top:1px solid #eceae5;color:#8a8679;font-size:11px;line-height:1.6;">
    This message was generated by the Vaanijya resolution agent. Money decisions
    on this platform are made by an audited rule engine, not by a language model.
    <br>Questions? Reply to this email and a person will read it.
  </td></tr>
</table></body></html>`;
}

function cell(inner: string): string {
  return `<tr><td style="padding:24px 26px;font-size:14px;line-height:1.65;color:#2b3444;">${inner}</td></tr>`;
}

function kv(rows: [string, string][]): string {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:14px 0;border:1px solid #eceae5;border-radius:10px;">
  ${rows
    .map(
      ([k, v], i) => `<tr${i % 2 ? ' style="background:#faf9f7;"' : ""}>
    <td style="padding:9px 14px;font-size:12px;color:#8a8679;width:42%;">${esc(k)}</td>
    <td style="padding:9px 14px;font-size:13px;font-weight:600;color:#17202a;">${v}</td></tr>`,
    )
    .join("")}
</table>`;
}

function button(label: string, href: string, accent = "#f97316"): string {
  return `<div style="margin:22px 0 6px;"><a href="${esc(href)}" style="display:inline-block;background:${accent};color:#fff;text-decoration:none;padding:11px 22px;border-radius:9px;font-size:14px;font-weight:600;">${esc(label)}</a></div>`;
}

/* ──────────────────────── Buyer: order confirmed ──────────────────────── */

export function orderPlaced(p: {
  name: string;
  orderNo: string;
  items: { title: string; qty: number; unitPriceInr: number }[];
  amountInr: number;
  paymentMode: string;
  promisedBy: Date;
  address: string;
  placedByAgent: boolean;
}) {
  const lines = p.items
    .map(
      (i) =>
        `<tr><td style="padding:7px 0;font-size:13px;">${esc(i.title)} <span style="color:#8a8679;">× ${i.qty}</span></td>
         <td align="right" style="padding:7px 0;font-size:13px;font-weight:600;">${INR(i.unitPriceInr * i.qty)}</td></tr>`,
    )
    .join("");

  const agentNote = p.placedByAgent
    ? `<div style="background:#fff7ed;border-left:3px solid #f97316;padding:11px 14px;border-radius:0 8px 8px 0;margin:4px 0 18px;font-size:13px;color:#7c3a0c;">
         Placed for you by the shopping agent from the requirements you described.
       </div>`
    : "";

  return {
    subject: `Order ${p.orderNo} confirmed — ${INR(p.amountInr)}`,
    html: shell(
      "Order confirmed",
      cell(`<p style="margin:0 0 14px;">Hello ${esc(p.name)},</p>
${agentNote}
<p style="margin:0 0 4px;">Your order is confirmed and being prepared for dispatch.</p>
<table role="presentation" width="100%" style="margin:16px 0;border-top:1px solid #eceae5;border-bottom:1px solid #eceae5;">${lines}
<tr><td style="padding:10px 0 0;font-size:14px;font-weight:700;">Total</td>
<td align="right" style="padding:10px 0 0;font-size:14px;font-weight:700;">${INR(p.amountInr)}</td></tr></table>
${kv([
  ["Order number", esc(p.orderNo)],
  ["Payment", esc(p.paymentMode === "COD" ? "Cash on delivery" : "Paid online")],
  ["Expected by", esc(p.promisedBy.toLocaleDateString("en-IN", { weekday: "short", day: "numeric", month: "short" }))],
  ["Delivering to", esc(p.address)],
])}
${button("Track this order", `${env.app.baseUrl}/orders/${encodeURIComponent(p.orderNo)}`)}`),
    ),
  };
}

/* ──────────────────── Buyer: delivery status change ──────────────────── */

export function orderStatus(p: {
  name: string;
  orderNo: string;
  status: string;
  headline: string;
  detail: string;
  promisedBy?: Date | null;
}) {
  const accent = p.status === "DELIVERED" ? "#0d9488" : "#f97316";
  return {
    subject: `${p.headline} — order ${p.orderNo}`,
    html: shell(
      p.headline,
      cell(`<p style="margin:0 0 12px;">Hello ${esc(p.name)},</p>
<p style="margin:0 0 10px;font-size:15px;font-weight:600;">${esc(p.headline)}</p>
<p style="margin:0 0 6px;color:#4a5568;">${esc(p.detail)}</p>
${kv([
  ["Order", esc(p.orderNo)],
  ["Status", esc(p.status.replace(/_/g, " ").toLowerCase())],
  ...(p.promisedBy
    ? ([["Expected by", esc(p.promisedBy.toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" }))]] as [string, string][])
    : []),
])}
${
  p.status === "DELIVERED"
    ? `<p style="margin:14px 0 0;font-size:13px;color:#4a5568;">Something wrong with it? You can report a problem in your own
         language — type it or record a voice note, add a photo, and the agent
         will take it from there.</p>
       ${button("Report a problem", `${env.app.baseUrl}/orders/${encodeURIComponent(p.orderNo)}/complaint`, "#0d9488")}`
    : button("Track this order", `${env.app.baseUrl}/orders/${encodeURIComponent(p.orderNo)}`, accent)
}`),
      accent,
    ),
  };
}

